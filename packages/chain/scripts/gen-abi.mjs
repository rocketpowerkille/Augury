// Generate src/abi/auguryHub.ts from Foundry's build output, so the TypeScript client can
// never drift from the contract. Run `forge build` in contracts/ first, then:
//   node scripts/gen-abi.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = join(here, "../../../contracts/out/AuguryHub.sol/AuguryHub.json");
const target = join(here, "../src/abi/auguryHub.ts");

const { abi, bytecode } = JSON.parse(readFileSync(artifact, "utf8"));
const source = `// Generated by scripts/gen-abi.mjs from contracts/out/AuguryHub.sol/AuguryHub.json.
// Do not edit by hand: change the contract, run \`forge build\`, then regenerate.

export const auguryHubAbi = ${JSON.stringify(abi, null, 2)} as const;

export const auguryHubBytecode = ${JSON.stringify(bytecode.object)} as const;
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, source);
console.log(`wrote ${target} (${abi.length} ABI entries)`);
