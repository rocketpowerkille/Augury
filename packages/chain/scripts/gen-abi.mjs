// Generate src/abi/*.ts from Foundry's build output, so the TypeScript client can never
// drift from the contracts. Run `forge build` in contracts/ first, then:
//   node scripts/gen-abi.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = [
  { name: "AuguryHub", file: "auguryHub.ts", exportName: "auguryHub" },
  { name: "PrivateFeeds", file: "privateFeeds.ts", exportName: "privateFeeds" },
  { name: "SettlementReceipts", file: "settlementReceipts.ts", exportName: "settlementReceipts" },
];

for (const c of contracts) {
  const artifact = join(here, `../../../contracts/out/${c.name}.sol/${c.name}.json`);
  const target = join(here, `../src/abi/${c.file}`);
  const { abi, bytecode } = JSON.parse(readFileSync(artifact, "utf8"));
  const source = `// Generated by scripts/gen-abi.mjs from contracts/out/${c.name}.sol/${c.name}.json.
// Do not edit by hand: change the contract, run \`forge build\`, then regenerate.

export const ${c.exportName}Abi = ${JSON.stringify(abi, null, 2)} as const;

export const ${c.exportName}Bytecode = ${JSON.stringify(bytecode.object)} as const;
`;
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, source);
  console.log(`wrote ${target} (${abi.length} ABI entries)`);
}
